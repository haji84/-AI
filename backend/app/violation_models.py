class CorrectionEvent(Base):
    __tablename__='correction_events'
    __table_args__=(UniqueConstraint('action_id','sequence_no',name='correction_event_sequence'),CheckConstraint("kind IN ('instruction','response','verification','completion','cancel','reopen')",name='correction_event_kind'))
    event_id:Mapped[str]=mapped_column(Uuid(as_uuid=False),primary_key=True,default=uuid_str)
    action_id:Mapped[str]=mapped_column(ForeignKey('corrective_actions.action_id'),nullable=False,index=True)
    sequence_no:Mapped[int]=mapped_column(BigInteger,nullable=False)
    kind:Mapped[str]=mapped_column(String(30),nullable=False)
    text:Mapped[str]=mapped_column(Text,nullable=False)
    human_reason:Mapped[str]=mapped_column(Text,nullable=False)
    verification_passed:Mapped[bool|None]=mapped_column(Boolean)
    source_snapshot:Mapped[dict]=mapped_column(JSON,nullable=False,default=dict)
    created_by:Mapped[str]=mapped_column(ForeignKey('app_users.user_id'),nullable=False)
    created_at:Mapped[object]=mapped_column(DateTime(timezone=True),default=now_utc)
