"""Formal cases remain independent of inspection observations and AI candidates."""
from sqlalchemy import BigInteger,Boolean,UniqueConstraint,CheckConstraint,Date,DateTime,ForeignKey,JSON,String,Text,Uuid
from sqlalchemy.orm import Mapped,mapped_column
from .db import Base
from .models import uuid_str,now_utc

class ViolationCase(Base):
    __tablename__='violation_cases'
    __table_args__=(CheckConstraint("status IN ('candidate','reviewed','confirmed','completed','resolved_candidate','withdrawn','superseded')",name='violation_case_status'),CheckConstraint("origin IN ('human','ai')",name='violation_case_origin'),CheckConstraint('version >= 1',name='violation_case_version'),)
    case_id:Mapped[str]=mapped_column(Uuid(as_uuid=False),primary_key=True,default=uuid_str)
    building_id:Mapped[str]=mapped_column(ForeignKey('facilities.building_id'),nullable=False,index=True)
    finding_id:Mapped[str|None]=mapped_column(ForeignKey('inspection_findings.finding_id'))
    supersedes_case_id:Mapped[str|None]=mapped_column(ForeignKey('violation_cases.case_id'))
    observed_on:Mapped[object]=mapped_column(Date,nullable=False)
    possible_issue:Mapped[str]=mapped_column(Text,nullable=False)
    missing_information:Mapped[list]=mapped_column(JSON,nullable=False,default=list)
    confirmation_steps:Mapped[list]=mapped_column(JSON,nullable=False,default=list)
    rule_version_ids:Mapped[list]=mapped_column(JSON,nullable=False,default=list)
    evidence_document_ids:Mapped[list]=mapped_column(JSON,nullable=False,default=list)
    procedure_document_ids:Mapped[list]=mapped_column(JSON,nullable=False,default=list)
    origin:Mapped[str]=mapped_column(String(20),nullable=False,default='human')
    ai_provenance:Mapped[dict]=mapped_column(JSON,nullable=False,default=dict)
    status:Mapped[str]=mapped_column(String(30),nullable=False,default='candidate',index=True)
    review_snapshot:Mapped[dict]=mapped_column(JSON,nullable=False,default=dict)
    reviewed_by:Mapped[str|None]=mapped_column(ForeignKey('app_users.user_id'))
    reviewed_at:Mapped[object|None]=mapped_column(DateTime(timezone=True))
    confirmed_by:Mapped[str|None]=mapped_column(ForeignKey('app_users.user_id'))
    confirmed_at:Mapped[object|None]=mapped_column(DateTime(timezone=True))
    last_human_reason:Mapped[str|None]=mapped_column(Text)
    created_by:Mapped[str]=mapped_column(ForeignKey('app_users.user_id'),nullable=False)
    created_at:Mapped[object]=mapped_column(DateTime(timezone=True),default=now_utc)
    updated_at:Mapped[object]=mapped_column(DateTime(timezone=True),default=now_utc)
    version:Mapped[int]=mapped_column(BigInteger,nullable=False,default=1)
    completed_by:Mapped[str|None]=mapped_column(ForeignKey('app_users.user_id'))
    completed_at:Mapped[object|None]=mapped_column(DateTime(timezone=True))

